public class dataType {
    public static void main(String[] args){
        byte a = 10;
        short b = 100;
        int c = 100000;
        char d = 'A';
        float e = 3.50f;
        double f = 3.4567;

        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
        System.out.println(e);
        System.out.println(f);
    }
}
